#!/usr/bin/env bash
# Installs the external tools Guardian wraps and records their versions in tools.lock.
#
# NOT VERIFIED when this kit was written (the authoring sandbox had no network): treat this as
# a starting point, fix it for your machine in phase 0, and keep tools.lock truthful.
# Strategy: Homebrew when available (macOS and Linux), pipx/uv for Python tools, and a clear
# message for anything that could not be installed. A missing tool is not fatal: Guardian
# reports the affected checks as "not run".
set -uo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

have() { command -v "$1" >/dev/null 2>&1; }
note() { printf '\n== %s\n' "$*"; }
MISSING=()

# Required: syft grype osv-scanner (plus docker). The rest is optional extra evidence.
BREW_TOOLS=(syft grype osv-scanner hadolint conftest cosign trivy)
PY_TOOLS=(zizmor guarddog semgrep)
[ "${GUARDIAN_REQUIRED_ONLY:-0}" = 1 ] && { BREW_TOOLS=(syft grype osv-scanner); PY_TOOLS=(); }

note "Prerequisites"
for t in git node npm python3 docker; do
  if have "$t"; then echo "ok       $t"; else echo "MISSING  $t  (install it yourself first)"; MISSING+=("$t"); fi
done
if have uv; then echo "ok       uv"; else
  echo "MISSING  uv  (install it: https://docs.astral.sh/uv/getting-started/installation/ ,"
  echo "             or use python -m venv + pip; then re-run this script)"; MISSING+=("uv")
fi

note "Scanner binaries"
if have brew; then
  for t in "${BREW_TOOLS[@]}"; do
    have "$t" || brew install "$t" || MISSING+=("$t")
  done
else
  echo "Homebrew not found. Install it (https://brew.sh, works on Linux too) or install these"
  echo "manually from their release pages: ${BREW_TOOLS[*]}"
  for t in "${BREW_TOOLS[@]}"; do have "$t" || MISSING+=("$t"); done
fi

note "Python-based tools (isolated with uv tool)"
for t in ${PY_TOOLS[@]+"${PY_TOOLS[@]}"}; do
  have "$t" || { have uv && uv tool install "$t"; } || MISSING+=("$t")
done

note "Vulnerability databases and images (so the demo works on bad wifi)"
have grype && grype db update || true
have trivy && trivy image --download-db-only || true
if have docker && docker info >/dev/null 2>&1; then
  docker pull node:18.13.0 || true
  docker pull node:18 || true
  docker pull mongo:3 || true
else
  echo "docker daemon not reachable: validation will be degraded until it is"
fi

note "Recording versions -> tools.lock"
{
  echo "# generated by scripts/setup_tools.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  for t in git node npm python3 docker uv "${BREW_TOOLS[@]}" ${PY_TOOLS[@]+"${PY_TOOLS[@]}"}; do
    if have "$t"; then
      v="$("$t" --version 2>/dev/null | head -1 || true)"
      [ -n "$v" ] || v="$("$t" version 2>/dev/null | head -1 || true)"
      echo "$t: ${v:-installed, version flag unknown}"
    else
      echo "$t: MISSING"
    fi
  done
} > tools.lock
cat tools.lock

if [ "${#MISSING[@]}" -gt 0 ]; then
  note "Could not install: ${MISSING[*]}"
  echo "Record each in docs/KNOWN_LIMITATIONS.md. Guardian must report their checks as 'not run'."
fi
exit 0

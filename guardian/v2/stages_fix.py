"""Stages 8-10 (M3): remedies (human gate), verify (sandbox proof), report. Any ecosystem.

- Plans are generated by code: "move <package> to the lowest version that fixes all of its known
  advisories". Edits are structured (file + exact change), turned into a reviewable patch in a
  throwaway clone, and bound to a plan_hash.
- Only a human click in the UI (routes_fix) approves a plan. No stage or agent code approves.
- Verify applies the APPROVED edits to a fresh clone, refreshes the lockfile with scripts disabled,
  rescans with the same tools and compares before/after. Tests run only in a container; without
  docker they are "not run" and the verdict can be at most PARTIAL.
"""

from __future__ import annotations

import datetime as dt
import hashlib
import json
import os
import re
import shutil
import subprocess
from pathlib import Path

from . import stages_detect as det
from .stages_discover import norm_name
from .tools import find_tool, tool_version
from .workspace import Workspace

HASHED = ("id", "component_id", "ecosystem", "name", "from_version", "to_version", "targets", "edits", "kind")


def _now() -> str:
    return dt.datetime.now(dt.UTC).isoformat(timespec="seconds")


def _run(cmd, cwd=None, timeout=600, env=None):
    return subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, encoding="utf-8", errors="replace",
                          timeout=timeout, env={**os.environ, "GIT_TERMINAL_PROMPT": "0", **(env or {})})


def plan_hash(plan: dict) -> str:
    body = {k: plan.get(k) for k in HASHED} | {"patch_sha256": plan.get("patch_sha256")}
    return hashlib.sha256(json.dumps(body, sort_keys=True, ensure_ascii=False).encode()).hexdigest()


def _clone(ws: Workspace, name: str) -> Path:
    d = ws.dir / "work" / name
    if d.exists():
        shutil.rmtree(d, onerror=lambda f, p, e: (os.chmod(p, 0o700), f(p)))
    d.parent.mkdir(parents=True, exist_ok=True)
    r = _run(["git", "-c", "core.autocrlf=false", "clone", "-q", "--no-hardlinks", "--no-recurse-submodules",
              "-c", f"core.hooksPath={ws.dir / '.nohooks'}", str(ws.src), str(d)])
    if r.returncode:
        raise RuntimeError(f"clone failed: {r.stderr.strip()[-200:]}")
    _run(["git", "config", "core.autocrlf", "false"], cwd=d)
    return d


# ---------------------------------------------------------------- edits
def apply_edit(root: Path, e: dict) -> None:
    p = root / e["file"]
    if e["kind"] == "replace_line":
        raw = p.read_bytes().decode("utf-8")
        lines = raw.splitlines(keepends=True)
        i = e["line"] - 1
        if i >= len(lines) or lines[i].rstrip("\r\n") != e["old"]:
            raise RuntimeError(f"{e['file']}:{e['line']} no longer reads {e['old']!r}")
        end = lines[i][len(lines[i].rstrip("\r\n")):]
        lines[i] = e["new"] + end
        p.write_bytes("".join(lines).encode("utf-8"))
    elif e["kind"] == "json_set":
        raw = p.read_bytes().decode("utf-8")
        j = json.loads(raw)
        cur = j
        for k in e["path"][:-1]:
            cur = cur.setdefault(k, {})
        cur[e["path"][-1]] = e["value"]
        indent = 2 if '\n  "' in raw else 4 if '\n    "' in raw else 2
        nl = "\r\n" if "\r\n" in raw else "\n"
        p.write_bytes((json.dumps(j, indent=indent, ensure_ascii=False) + "\n").replace("\n", nl).encode("utf-8"))
    else:
        raise RuntimeError(f"unknown edit kind {e['kind']}")


def _req_edit(src: Path, ing: dict, name: str, old: str, new: str) -> dict | None:
    for f in (ing.get("ecosystems", {}).get("pypi", {}) or {}).get("manifests", []):
        if not Path(f).name.startswith("requirements"):
            continue
        for i, ln in enumerate((src / f).read_bytes().decode("utf-8", "replace").splitlines(), 1):
            m = re.match(r"^(\s*)([A-Za-z0-9_.\-\[\]]+)(\s*==\s*)([^\s;#]+)(.*)$", ln)
            if m and norm_name("pypi", re.sub(r"\[.*\]", "", m.group(2))) == norm_name("pypi", name) and m.group(4) == old:
                return {"file": f, "kind": "replace_line", "line": i, "old": ln,
                        "new": f"{m.group(1)}{m.group(2)}{m.group(3)}{new}{m.group(5)}"}
    return None


def _npm_edit(src: Path, name: str, new: str) -> dict | None:
    p = src / "package.json"
    if not p.exists():
        return None
    j = json.loads(p.read_text(encoding="utf-8"))
    for sec in ("dependencies", "devDependencies", "optionalDependencies"):
        if name in (j.get(sec) or {}):
            return {"file": "package.json", "kind": "json_set", "path": [sec, name], "value": new,
                    "note": f"direct dependency: set {sec}.{name} to {new}"}
    return {"file": "package.json", "kind": "json_set", "path": ["overrides", name], "value": new,
            "note": f"transitive dependency: npm overrides forces {name}@{new} wherever it is required"}


def _pick_version(installed: str | None, rows: list[dict]) -> tuple[str | None, list[str]]:
    """Lowest version that is >= a fix of every advisory with a fix; advisories without a fix are listed."""
    need, nofix = None, []
    iv = det._vkey(installed or "0")
    for r in rows:
        later = sorted((f for f in r["fixed"] if det._vkey(f) > iv), key=det._vkey)
        if not later:
            nofix.append(r["advisory"])
            continue
        if need is None or det._vkey(later[0]) > det._vkey(need):
            need = later[0]
    return need, nofix


# ---------------------------------------------------------------- stage 8: remedies
def run_remedies(ws: Workspace, opts: dict) -> dict:
    pri, vul, ing = ws.read("prioritise") or {"items": []}, ws.read("vulns") or {"rows": []}, ws.read("ingest") or {}
    top = int(opts.get("top") or 10)
    by_comp: dict[str, list] = {}
    for r in vul["rows"]:
        by_comp.setdefault(r["component_id"], []).append(r)
    chosen, seen = [], set()
    for it in pri["items"]:
        r0 = (by_comp.get(it.get("component_id")) or [None])[0]
        name_key = (r0["ecosystem"], norm_name(r0["ecosystem"], r0["name"])) if r0 else None
        if it["kind"] == "vuln" and r0 and name_key not in seen:  # one plan per package (all installed versions)
            seen.add(name_key)
            chosen.append(it)
        if len(chosen) >= top:
            break
    out = ws.stage_dir("remedies")
    for old in out.glob("P-*.patch"):
        old.unlink()
    clone = _clone(ws, "plan") if chosen else None
    plans = []
    for n, it in enumerate(chosen, 1):
        rows = by_comp[it["component_id"]]
        r0 = rows[0]
        eco, name, ver = r0["ecosystem"], r0["name"], r0["version"]
        to, nofix = _pick_version(ver, rows)
        pid = f"P-{n:04d}"
        plan = {"id": pid, "component_id": it["component_id"], "ecosystem": eco, "name": name, "from_version": ver,
                "to_version": to, "targets": sorted(r["advisory"] for r in rows if r["advisory"] not in nofix),
                "unfixable": nofix, "priority": {"rank": it["rank"], "score": it["score"], "band": it["band"]},
                "edits": [], "kind": "upgrade", "decision": {"status": "pending"}, "patch": None, "patch_sha256": None}
        edit = None
        if to and eco == "pypi":
            edit = _req_edit(ws.src, ing, name, ver, to)
        elif to and eco == "npm":
            edit = _npm_edit(ws.src, name, to)
        if not to:
            plan.update(kind="manual", reason="no fixed version is published for these advisories")
        elif not edit:
            plan.update(kind="manual", reason=(f"no exact pin for {name} found in a manifest Guardian can edit "
                                               f"({eco}); upgrade it by hand or through its parent package"))
        else:
            plan["edits"] = [edit]
            try:
                apply_edit(clone, edit)
                diff = _run(["git", "diff", "--no-color"], cwd=clone).stdout
                _run(["git", "checkout", "--", "."], cwd=clone)
                pb = diff.encode("utf-8")
                (out / f"{pid}.patch").write_bytes(pb)
                plan["patch"], plan["patch_sha256"] = ws.rel(out / f"{pid}.patch"), hashlib.sha256(pb).hexdigest()
            except Exception as e:  # noqa: BLE001 - recorded on the plan, shown to the human
                plan.update(kind="manual", reason=f"edit could not be prepared: {e}", edits=[])
        plan["lockfile_note"] = ("npm: the lockfile is regenerated in the sandbox with --package-lock-only --ignore-scripts"
                                 if eco == "npm" else "requirements pins are the lock: no regeneration needed"
                                 if eco == "pypi" else None)
        plan["why"] = (f"Ranked #{it['rank']} ({it['band']}, {it['score']}). Moving {name} {ver} → {to} fixes "
                       f"{len(plan['targets'])} advisory(ies): {', '.join(plan['targets'][:6])}"
                       + (f"; no fix exists yet for {', '.join(nofix)}" if nofix else "") + "." if to else
                       f"Ranked #{it['rank']}; no fixed version published.")
        plan["rollback"] = "revert the patch (git revert) or restore the previous version pin"
        plan["plan_hash"] = plan_hash(plan)
        plans.append(plan)
    result = {"plans": plans, "sent": False, "approved_set": None,
              "note": "Plans are computed by code from the advisories' fixed versions. Approve, reject or defer each "
                      "one; only approved plans go to the sandbox. The approval is bound to plan_hash."}
    ws.write("remedies", result)
    summary = _summary(result)
    ws.set_status("remedies", "awaiting_approval", summary=summary)
    return summary


def _summary(res: dict) -> dict:
    ps = res["plans"]
    actionable = [p for p in ps if p["kind"] != "manual"]
    return {"plans": len(ps), "actionable": len(actionable),
            "decided": sum(1 for p in actionable if p["decision"]["status"] != "pending"),
            "approved": sum(1 for p in actionable if p["decision"]["status"] == "approved")}


# decisions are made ONLY through guardian/api/routes_fix.py (a human click); kept here as pure helpers
def record_decision(ws: Workspace, plan_id: str, decision: str, approver: str, hash_shown: str, note: str = "") -> dict:
    res = ws.read("remedies")
    if not res:
        raise LookupError("no remedies yet")
    if res.get("sent"):
        raise PermissionError("the approved set was already sent to the sandbox; re-run remedies to change it")
    plan = next((p for p in res["plans"] if p["id"] == plan_id), None)
    if not plan:
        raise LookupError(f"no plan {plan_id}")
    if decision not in ("approve", "reject", "defer"):
        raise ValueError("decision must be approve, reject or defer")
    if not (approver or "").strip():
        raise ValueError("approver name is required")
    if plan["kind"] == "manual" and decision == "approve":
        raise ValueError("a manual plan cannot be approved: it has no edit to apply")
    if hash_shown != plan["plan_hash"] or plan_hash(plan) != plan["plan_hash"]:
        raise PermissionError("plan_hash mismatch: the plan changed since it was shown; reload and review it again")
    plan["decision"] = {"status": {"approve": "approved", "reject": "rejected", "defer": "deferred"}[decision],
                        "by": approver.strip(), "at": _now(), "note": note, "plan_hash": plan["plan_hash"]}
    ws.write("remedies", res)
    ws.set_status("remedies", "awaiting_approval", summary=_summary(res))
    ws.audit(f"plan_{decision}", actor=approver.strip(), plan=plan_id, plan_hash=plan["plan_hash"], note=note)
    return plan


def freeze_approved(ws: Workspace) -> dict:
    res = ws.read("remedies")
    act = [p for p in res["plans"] if p["kind"] != "manual"]
    if any(p["decision"]["status"] == "pending" for p in act):
        raise ValueError("decide every plan first (approve, reject or defer)")
    appr = [p for p in act if p["decision"]["status"] == "approved"]
    if not appr:
        raise ValueError("approve at least one plan to send to the sandbox")
    aset = {"at": _now(), "plans": [{"id": p["id"], "plan_hash": p["plan_hash"], "by": p["decision"]["by"]} for p in appr]}
    (ws.stage_dir("remedies") / "approved_set.json").write_text(json.dumps(aset, indent=2), encoding="utf-8")
    res["sent"], res["approved_set"] = True, ws.rel(ws.stage_dir("remedies") / "approved_set.json")
    ws.write("remedies", res)
    ws.set_status("remedies", "ok", summary=_summary(res))
    ws.audit("send_to_sandbox", actor=appr[0]["decision"]["by"], plans=[p["id"] for p in appr])
    return aset


# ---------------------------------------------------------------- container tests
IMAGES = {"npm": "node:20-bookworm-slim", "pypi": "python:3.12-slim", "golang": "golang:1.22"}
LIMITS = ["--memory", "2g", "--cpus", "2", "--pids-limit", "512", "--security-opt", "no-new-privileges"]


def _docker() -> str | None:
    exe = find_tool("docker")
    for cand in ("C:/Program Files/Docker/Docker/resources/bin/docker.exe",):
        if not exe and Path(cand).exists():
            exe = cand
    return exe


def test_plan(clone: Path) -> dict | None:
    """Which ecosystem's tests to run and how: (install step with network, test step without)."""
    pj = clone / "package.json"
    if pj.exists():
        t = (json.loads(pj.read_text(encoding="utf-8")).get("scripts") or {}).get("test", "")
        if t and "no test specified" not in t:
            return {"eco": "npm", "install": "npm ci || npm install", "test": "npm test"}
    if any((clone / f).exists() for f in ("requirements.txt", "pyproject.toml", "setup.py")):
        has_tests = any(clone.glob("test*/**/*.py")) or any(clone.glob("**/test_*.py")) or (clone / "pytest.ini").exists()
        if has_tests:
            req = "pip install -r requirements.txt" if (clone / "requirements.txt").exists() else "pip install ."
            return {"eco": "pypi", "install": f"python -m venv /app/.gv && . /app/.gv/bin/activate && {req} && pip install pytest",
                    "test": ". /app/.gv/bin/activate && python -m pytest -q"}
    if (clone / "go.mod").exists():
        return {"eco": "golang", "install": "GOMODCACHE=/app/.gomod go mod download",
                "test": "GOMODCACHE=/app/.gomod GOFLAGS=-mod=mod go test ./..."}
    return None


def docker_cmd(docker: str, clone: Path, image: str, script: str, network: bool) -> list[str]:
    """No env passthrough, no host mounts except the clone; the test step has no network."""
    return [docker, "run", "--rm", *LIMITS, *([] if network else ["--network", "none"]),
            "-v", f"{clone}:/app", "-w", "/app", image, "sh", "-c", script]


def _counts(text: str) -> str | None:
    pats = [r"(\d+) passed(?:, (\d+) failed)?", r"(\d+) passing(?:[\s\S]*?(\d+) failing)?", r"Tests:\s+(?:(\d+) failed, )?(\d+) passed"]
    for p in pats:
        m = re.search(p, text)
        if m:
            return " ".join(m.group(0).split())[:80]
    return None


def container_tests(clone: Path, approved: list, out: Path, ws: Workspace) -> dict:
    plan = test_plan(clone)
    if not plan:
        return _check("tests", "not-run", "no test suite found in the repository (nothing to run)")
    docker = _docker()
    if not docker:
        return _check("tests", "not-run", "docker is not installed: the repository's tests were NOT run "
                      "(they run only inside an isolated container)")
    if _run([docker, "info"], timeout=30).returncode:
        return _check("tests", "not-run", "docker is installed but the daemon is not running (start Docker Desktop)")
    image = IMAGES[plan["eco"]]
    log = out / "tests.log"
    r1 = _run(docker_cmd(docker, clone, image, plan["install"], network=True), timeout=1200)
    r2 = _run(docker_cmd(docker, clone, image, plan["test"], network=False), timeout=1200) if r1.returncode == 0 else None
    parts = [f"$ {plan['install']}", r1.stdout, r1.stderr]
    if r2:
        parts += [f"$ {plan['test']}  (network: none)", r2.stdout, r2.stderr]
    log.write_text("\n".join(parts), encoding="utf-8")
    if r1.returncode:
        return _check("tests", "fail", f"dependencies did not install in the container (exit {r1.returncode})", ws.rel(log))
    n = _counts(r2.stdout + r2.stderr)
    return _check("tests", "pass" if r2.returncode == 0 else "fail",
                  f"{plan['test']} in {image}, network none: exit {r2.returncode}" + (f" ({n})" if n else ""), ws.rel(log))


# ---------------------------------------------------------------- stage 9: verify
def _check(name, status, detail, log=None):
    return {"name": name, "status": status, "detail": detail, "log": log}


def run_verify(ws: Workspace, opts: dict) -> dict:
    res = ws.read("remedies") or {}
    out = ws.stage_dir("verify")
    aset_p = ws.dir / "stages" / "remedies" / "approved_set.json"
    if not res.get("sent") or not aset_p.exists():
        raise RuntimeError("no approved set: approve plans on the Remedies page and press 'Send to sandbox'")
    aset = json.loads(aset_p.read_text(encoding="utf-8"))
    plans = {p["id"]: p for p in res["plans"]}
    checks, approved = [], []
    for a in aset["plans"]:
        p = plans.get(a["id"])
        ok = p and p["decision"]["status"] == "approved" and plan_hash(p) == a["plan_hash"] == p["plan_hash"]
        if not ok:
            checks.append(_check("approval", "fail", f"{a['id']}: plan changed after approval (hash mismatch)"))
        else:
            approved.append(p)
    if approved and not checks:
        checks.append(_check("approval", "pass", f"{len(approved)} plan(s) approved by "
                             f"{', '.join(sorted({p['decision']['by'] for p in approved}))}; hashes match"))
    clone = _clone(ws, "verify")
    # 1. apply
    try:
        for p in approved:
            for e in p["edits"]:
                apply_edit(clone, e)
        diff = _run(["git", "diff", "--stat"], cwd=clone).stdout
        (out / "applied.diff").write_text(_run(["git", "diff"], cwd=clone).stdout, encoding="utf-8")
        checks.append(_check("apply", "pass", f"approved edits applied to a fresh clone: {diff.strip().splitlines()[-1] if diff.strip() else 'no change'}",
                             ws.rel(out / "applied.diff")))
    except Exception as e:  # noqa: BLE001
        checks.append(_check("apply", "fail", str(e)))
    # 2. lockfile
    if any(p["ecosystem"] == "npm" for p in approved) and (clone / "package-lock.json").exists():
        npm = find_tool("npm") or shutil.which("npm.cmd")
        if not npm:
            checks.append(_check("lockfile", "not-run", "npm not installed"))
        else:
            r = _run([npm, "install", "--package-lock-only", "--ignore-scripts", "--no-audit", "--no-fund"], cwd=clone, timeout=900)
            (out / "npm-lock.log").write_text(r.stdout + "\n" + r.stderr, encoding="utf-8")
            checks.append(_check("lockfile", "pass" if r.returncode == 0 else "fail",
                                 "package-lock.json regenerated with --package-lock-only --ignore-scripts (no code run)"
                                 if r.returncode == 0 else f"npm exit {r.returncode}", ws.rel(out / "npm-lock.log")))
    else:
        checks.append(_check("lockfile", "pass", "requirements pins are the lock; nothing to regenerate"))
    # 3. tests: the ONLY place repository code runs, and only inside an isolated container
    checks.append(container_tests(clone, approved, out, ws))
    # 4. rescan with the same tools as stage 4
    after_records, tools = [], {}
    ing = ws.read("ingest") or {}
    targets = det._osv_targets(ing)
    exe = find_tool("osv-scanner")
    if exe and targets and not det._offline():
        cmd = [exe, "scan", "source", "--format", "json"]
        for _, f in targets:
            cmd += ["-L", (f"requirements.txt:{f}" if Path(f).name.startswith("requirements") else f)]
        r = _run(cmd, cwd=clone)
        if r.returncode in (0, 1) and r.stdout.strip():
            (out / "rescan-osv-scanner.json").write_text(r.stdout, encoding="utf-8")
            after_records += det.records_from_osv_scanner(json.loads(r.stdout))
            tools["osv_scanner"] = "ran"
        else:
            tools["osv_scanner"] = f"failed (exit {r.returncode})"
    else:
        tools["osv_scanner"] = "not-run"
    syft, grype = find_tool("syft"), find_tool("grype")
    if syft and grype:
        sb = out / "rescan-syft.cdx.json"
        _run([syft, "scan", f"dir:{clone}", "-q", "-o", f"cyclonedx-json={sb}", "--exclude", "./**/node_modules/**",
              "--exclude", "./**/.git/**"], env={"SYFT_JAVASCRIPT_INCLUDE_DEV_DEPENDENCIES": "true", "SYFT_CHECK_FOR_APP_UPDATE": "false"})
        r = _run([grype, f"sbom:{sb}", "-o", "json", "-q"], env={"GRYPE_DB_CACHE_DIR": str(det.GRYPE_DB),
                                                                  "GRYPE_CHECK_FOR_APP_UPDATE": "false", "GRYPE_DB_AUTO_UPDATE": "false"})
        if r.returncode in (0, 1) and r.stdout.strip():
            (out / "rescan-grype.json").write_text(r.stdout, encoding="utf-8")
            after_records += det.records_from_grype(json.loads(r.stdout))
            tools["grype"] = "ran"
        else:
            tools["grype"] = f"failed (exit {r.returncode})"
    else:
        tools["grype"] = "not-run"
    ran = [k for k, v in tools.items() if v == "ran"]
    checks.append(_check("rescan", "pass" if ran else "not-run", f"tools on the patched clone: {tools}",
                         ws.rel(out / "rescan-osv-scanner.json") if (out / "rescan-osv-scanner.json").exists() else None))
    # 5. compare before / after (by package name + alias overlap)
    before = (ws.read("vulns") or {}).get("rows", [])

    def key(eco, name):
        return (eco, norm_name(eco, name or ""))

    after_by_pkg: dict = {}
    for rec in after_records:
        after_by_pkg.setdefault(key(rec["ecosystem"], rec["name"] or ""), []).append(rec)
    per_plan, new = [], []
    for p in approved:
        recs = after_by_pkg.get(key(p["ecosystem"], p["name"]), [])
        gone, still = [], []
        for adv in p["targets"]:
            brow = next((b for b in before if b["advisory"] == adv and b["component_id"] == p["component_id"]), None)
            ids = {adv, *(brow or {}).get("aliases", [])}
            (still if any(r["ids"] & ids for r in recs) else gone).append(adv)
        before_ids = {i for b in before if key(b["ecosystem"], b["name"]) == key(p["ecosystem"], p["name"])
                      for i in [b["advisory"], *b["aliases"]]}
        for r in recs:
            if not (r["ids"] & before_ids):
                new.append({"package": p["name"], "version": r.get("version"), "ids": sorted(r["ids"]), "tool": r["tool"]})
        per_plan.append({"plan": p["id"], "package": p["name"], "from": p["from_version"], "to": p["to_version"],
                         "targets": len(p["targets"]), "gone": gone, "still_present": still})
    targeted = {(p["component_id"], a) for p in approved for a in p["targets"]}
    remaining = [{"name": b["name"], "version": b["version"], "advisory": b["advisory"], "severity": b["severity"]}
                 for b in before if (b["component_id"], b["advisory"]) not in targeted]
    fixed = sum(len(x["gone"]) for x in per_plan)
    total = sum(x["targets"] for x in per_plan)
    still = sum(len(x["still_present"]) for x in per_plan)
    if ran:
        checks.append(_check("targets_fixed", "pass" if still == 0 and total else "fail",
                             f"{fixed} of {total} targeted advisories are gone after the fix"))
        checks.append(_check("no_new_vulnerabilities", "pass" if not new else "fail",
                             f"{len(new)} advisory(ies) newly reported on the upgraded packages"))
    else:
        checks.append(_check("targets_fixed", "not-run", "no scanner ran on the patched clone: cannot claim anything is fixed"))
    statuses = [c["status"] for c in checks]
    verdict = "FAILED" if "fail" in statuses else "PARTIAL" if "not-run" in statuses else "VERIFIED"
    result = {"verdict": verdict, "checks": checks, "per_plan": per_plan, "new_vulnerabilities": new,
              "remaining": remaining, "approved_set": res.get("approved_set"), "tools": tools,
              "headline": (f"Targeted vulnerabilities fixed: {fixed} of {total} · new: {len(new)} · tests: "
                           f"{next(c['status'] for c in checks if c['name'] == 'tests').replace('-', ' ')} · "
                           f"remaining (not covered by an approved plan): {len(remaining)}"),
              "why_verdict": {"VERIFIED": "every check passed, including the tests in a container",
                              "PARTIAL": "every check that ran passed, but at least one check did not run: "
                                         + ", ".join(c["name"] for c in checks if c["status"] == "not-run"),
                              "FAILED": "at least one check failed: " + ", ".join(c["name"] for c in checks if c["status"] == "fail")}[verdict],
              "clone": ws.rel(clone / ".git" / "HEAD") if (clone / ".git" / "HEAD").exists() else None}
    ws.write("verify", result)
    ws.audit("verify", verdict=verdict, fixed=fixed, total=total, new=len(new))
    return {"verdict": verdict, "fixed": f"{fixed}/{total}", "new": len(new), "remaining": len(remaining)}


# ---------------------------------------------------------------- stage 10: report
def run_report(ws: Workspace, opts: dict) -> dict:
    from . import runner
    m = ws.meta
    stages = []
    for s in runner.ORDER[:-1]:
        st = m.get("stages", {}).get(s, {})
        stages.append({"stage": s, "title": runner.TITLES[s], "status": st.get("status", "not_run"),
                       "summary": st.get("summary"), "finished": st.get("finished"),
                       "file": f"stages/{s}/result.json" if (ws.dir / "stages" / s / "result.json").exists() else None})
    sb, vu, pr, rm, vf = (ws.read(x) or {} for x in ("sbom", "vulns", "prioritise", "remedies", "verify"))
    rep = {"generated": _now(), "workspace": ws.id, "source": m["source"], "sha": m.get("sha"), "consent": m.get("consent"),
           "stages": stages,
           "sbom": (sb.get("totals") or {}), "vulnerabilities": (vu.get("counts") or {}),
           "tools": {k: {"status": v.get("status"), "version": v.get("version")} for k, v in (vu.get("tools") or {}).items()},
           "top_risks": [{k: it[k] for k in ("rank", "title", "score", "band", "why")} for it in (pr.get("items") or [])[:10]],
           "plans": [{"id": p["id"], "package": p["name"], "from": p["from_version"], "to": p["to_version"],
                      "decision": p["decision"]} for p in (rm.get("plans") or [])],
           "verification": {k: vf.get(k) for k in ("verdict", "headline", "why_verdict")} if vf else {"verdict": "not run"},
           "tool_versions": {t: tool_version(t) for t in ("syft", "osv-scanner", "grype")}}
    from ..audit import verify as audit_verify
    ok, msg = audit_verify(ws.dir) if (ws.dir / "audit.jsonl").exists() else (False, "no audit log")
    rep["audit"] = {"ok": ok, "detail": msg}
    out = ws.stage_dir("report")
    (out / "report.json").write_text(json.dumps(rep, indent=2, ensure_ascii=False), encoding="utf-8")
    md = [f"# Guardian report: {m['source'].get('value')}", "", f"Commit `{m.get('sha')}` · generated {rep['generated']}", "",
          "## Stages", *[f"- **{s['title']}**: {s['status']}" for s in stages], "",
          "## SBOM", f"{rep['sbom'].get('components', 'not run')} components", "",
          "## Vulnerabilities", json.dumps(rep["vulnerabilities"].get("by_severity", "not run")), "",
          "## Top risks", *[f"{t['rank']}. {t['title']} ({t['band']} {t['score']}): {t['why']}" for t in rep["top_risks"]], "",
          "## Remedies", *[f"- {p['id']} {p['package']} {p['from']} → {p['to']}: {p['decision']['status']}" for p in rep["plans"]], "",
          "## Sandbox verification", f"**{rep['verification'].get('verdict')}**: {rep['verification'].get('headline', '')}", "",
          f"Audit chain: {'OK' if ok else 'NOT OK'} ({msg})"]
    (out / "report.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    rep["files"] = {"json": ws.rel(out / "report.json"), "md": ws.rel(out / "report.md"), "audit": "audit.jsonl",
                    "sbom_cdx": (sb.get("files") or {}).get("syft_cdx"), "sbom_spdx": (sb.get("files") or {}).get("syft_spdx")}
    ws.write("report", rep)
    return {"stages_ok": sum(1 for s in stages if s["status"] in ("ok", "awaiting_approval")), "verdict": rep["verification"].get("verdict"),
            "audit": "ok" if ok else "not ok"}
